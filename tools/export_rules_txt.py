#!/usr/bin/env python3
"""Export every i-have-autism rule into one plain-text file.

Two rulesets ship in this repository and they are not the same thing:

- `skills/i-have-autism/SKILL.md` — the full ruleset, read on demand.
- `hermes/rules.md` — the condensed ruleset, injected into a system prompt
  where the platform caps a section at 4,000 characters (Cursor's always-on
  rule is generated from this same file).

The export strips markdown emphasis, turns headings into underlined titles and
keeps fenced code as indented blocks, so the file reads the same in a terminal,
a text editor, or a notes app.

Usage:
    python3 tools/export_rules_txt.py [output]
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = ROOT / "i-have-autism-rules.txt"

FULL = ROOT / "skills" / "i-have-autism" / "SKILL.md"
SHORT = ROOT / "hermes" / "rules.md"


def strip_frontmatter(text: str) -> str:
    if not text.startswith("---"):
        return text
    end = text.find("\n---", 3)
    return text[end + 4 :] if end != -1 else text


def to_plain(markdown: str) -> str:
    lines = strip_frontmatter(markdown).strip().splitlines()
    out: list[str] = []
    in_code = False

    for line in lines:
        if line.startswith("```"):
            in_code = not in_code
            out.append("")
            continue

        if in_code:
            out.append("    " + line)
            continue

        heading = re.match(r"^(#{1,6})\s+(.*)$", line)
        if heading:
            title = re.sub(r"\*\*|`", "", heading.group(2)).strip()
            out.append("")
            out.append(title)
            out.append("-" * min(len(title), 72))
            continue

        text = line.replace("**", "").replace("`", "")
        text = re.sub(r"\*([^*\n]+)\*", r"\1", text)
        text = re.sub(r"^\s*---\s*$", "", text)
        out.append(text.rstrip())

    cleaned: list[str] = []
    for line in out:
        if line == "" and cleaned and cleaned[-1] == "":
            continue
        cleaned.append(line)
    return "\n".join(cleaned).strip()


def build() -> str:
    full = to_plain(FULL.read_text(encoding="utf-8"))
    short = to_plain(SHORT.read_text(encoding="utf-8"))

    return (
        "I HAVE AUTISM — ALL RULES\n"
        "=========================\n\n"
        "Two rulesets, one standard.\n\n"
        "  PART 1  the full ruleset — 648 lines, read on demand by a coding agent\n"
        "  PART 2  the condensed ruleset — 3,838 characters, injected into a system\n"
        "          prompt where the platform caps a section at 4,000 characters\n\n"
        "Source of truth: https://github.com/Siririn77/i-have-autism\n"
        "Generated by tools/export_rules_txt.py. PART 2 is generated from\n"
        "hermes/rules.md, which is also the source of the Cursor always-on rule:\n"
        "edit that file, never one of its copies.\n\n"
        "Stop phrase: \"stop autism mode\" or \"normal mode\".\n\n\n"
        "==============================================================\n"
        "PART 1 — THE FULL RULESET\n"
        "==============================================================\n\n"
        f"{full}\n\n\n"
        "==============================================================\n"
        "PART 2 — THE CONDENSED RULESET (system-prompt budget)\n"
        "==============================================================\n\n"
        f"{short}\n"
    )


def main(argv: list[str]) -> int:
    out = Path(argv[0]) if argv else DEFAULT_OUT
    text = build()
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out} — {len(text)} chars, {len(text.splitlines())} lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
