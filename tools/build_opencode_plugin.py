#!/usr/bin/env python3
"""Build a self-contained opencode plugin package from the canonical skill.

Why a build step instead of shipping the repo file. `.opencode/plugins/i-have-autism.mjs`
reads the ruleset from `../../skills/i-have-autism/SKILL.md` and the command from
`../command/i-have-autism.md`. That only works inside this repository. A plugin
installed through npm or copied into `~/.config/opencode/plugins/` has no such
neighbours, so the packaged plugin must carry its own text.

The rules are therefore embedded at build time from the same SKILL.md the other
clients read. Nothing is retyped, and `--check` fails when the committed package
drifts from the current ruleset.

    python3 tools/build_opencode_plugin.py           # write dist/opencode-plugin
    python3 tools/build_opencode_plugin.py --check   # exit 1 if it is stale
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKILL = ROOT / "skills" / "i-have-autism" / "SKILL.md"
COMMAND = ROOT / ".opencode" / "command" / "i-have-autism.md"
PACKAGE = ROOT / "package.json"
OUT = ROOT / "dist" / "opencode-plugin"

PLUGIN_NAME = "opencode-i-have-autism"


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    """Split leading YAML frontmatter from the body.

    Only the flat `key: value` form used by SKILL.md is handled; nested YAML is
    not part of the contract, and guessing at it would be worse than failing.
    """
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}, text.rstrip("\n")
    for index in range(1, len(lines)):
        if lines[index].strip() == "---":
            meta: dict[str, str] = {}
            for raw in lines[1:index]:
                key, sep, value = raw.partition(":")
                if sep:
                    meta[key.strip()] = value.strip().strip('"').strip("'")
            return meta, "\n".join(lines[index + 1:]).rstrip("\n")
    return {}, text.rstrip("\n")


def skill_parts() -> tuple[str, str, str]:
    meta, body = split_frontmatter(SKILL.read_text(encoding="utf-8"))
    name = meta.get("name", "i-have-autism")
    description = meta.get("description", "")
    if not description:
        sys.exit("SKILL.md has no description in its frontmatter")
    return name, description, body


def command_parts() -> tuple[str, str]:
    raw = COMMAND.read_text(encoding="utf-8")
    if not raw.startswith("---\n"):
        sys.exit(".opencode/command/i-have-autism.md has no frontmatter")
    _, rest = raw.split("---\n", 1)
    head, _, template = rest.partition("\n---\n")
    description = json.loads(head).get("description", "")
    return description, template.strip()


JS = """\
// Generated by tools/build_opencode_plugin.py — do not edit by hand.
// Source of truth: skills/i-have-autism/SKILL.md.
//
// Self-contained: the ruleset, its description and the slash command are
// embedded below, so this file works when copied alone into
// ~/.config/opencode/plugins/ or installed from npm.
//
// Two runtime APIs are covered: V2 calls setup(), V1 calls server().
// The always-on path pushes a text part into the system array, never into the
// visible conversation, so it costs no user-visible turn.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

export const SKILL_ID = {name_json};

const DESCRIPTION = {description_json};

const RULESET = {body_json};

const COMMAND = {{
  description: {command_description_json},
  template: {command_template_json},
}};

const flagPath = path.join(
  process.env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config'),
  'opencode',
  '.i-have-autism-always',
);

function alwaysOnInjection() {{
  const envOn = ['1', 'true', 'yes'].includes(String(process.env.I_HAVE_AUTISM_ALWAYS || '').toLowerCase());
  let fileOn = false;
  try {{
    fileOn = fs.existsSync(flagPath);
  }} catch {{
    fileOn = false;
  }}
  if (!envOn && !fileOn) return null;

  const header =
    'AUTISM MODE ACTIVE (always-on). The ruleset below applies to every ' +
    'response. "stop autism mode" or "normal mode" turns it off for this ' +
    'session; delete ' + flagPath + ' to turn always-on off for good.';
  return header + '\\n\\n' + RULESET;
}}

export default {{
  id: SKILL_ID,

  async setup(ctx) {{
    try {{
      await ctx.skill.transform((editor) => {{
        if (editor.get(SKILL_ID)) return;
        editor.add({{
          id: SKILL_ID,
          name: SKILL_ID,
          description: DESCRIPTION,
          content: RULESET,
        }});
      }});
    }} catch {{
      // Keep the command available if skill registration fails.
    }}

    try {{
      await ctx.command.transform((editor) => {{
        editor.add({{
          name: SKILL_ID,
          description: COMMAND.description || DESCRIPTION,
          execute: ({{ sessionID, prompt, delivery }}) =>
            ctx.session.prompt({{
              ...prompt,
              sessionID,
              text: prompt.text ? `${{COMMAND.template}}\\n\\n${{prompt.text}}` : COMMAND.template,
              delivery,
            }}),
        }});
      }});
    }} catch {{
      // Keep skill discovery available if command registration fails.
    }}

    try {{
      await ctx.session.hook('context', (event) => {{
        const injected = alwaysOnInjection();
        if (!injected) return;
        event.system.push({{ type: 'text', text: injected }});
      }});
    }} catch {{
      // Optional hook failures must not block plugin loading.
    }}
  }},

  async server() {{
    return {{
      config: async (config) => {{
        config.command = config.command || {{}};
        if (!config.command[SKILL_ID]) {{
          config.command[SKILL_ID] = COMMAND;
        }}
      }},

      'experimental.chat.system.transform': async (_input, output) => {{
        const injected = alwaysOnInjection();
        if (!injected) return;

        if (output.system.length > 0) {{
          output.system[output.system.length - 1] += '\\n\\n' + injected;
        }} else {{
          output.system.push(injected);
        }}
      }},
    }};
  }},
}};
"""

README = """\
# opencode-i-have-autism

An opencode plugin that installs the **i-have-autism** ruleset: literal meaning,
every implicit step named, no social padding, direct disagreement, and code held
to correctness, readability and maintainability.

Generated from `skills/i-have-autism/SKILL.md`, version {version}.

## Install

Into the global plugin directory (one file, no dependencies):

```bash
mkdir -p ~/.config/opencode/plugins
cp i-have-autism.js ~/.config/opencode/plugins/
```

For one project only:

```bash
mkdir -p .opencode/plugins
cp i-have-autism.js .opencode/plugins/
```

From npm, once published:

```json
{{ "plugin": ["opencode-i-have-autism"] }}
```

## What it registers

- the `i-have-autism` skill, so `/skill:i-have-autism` loads the ruleset on demand;
- the `/i-have-autism` command, which applies the ruleset for the rest of the session;
- an **opt-in** always-on hook that puts the ruleset into the system prompt on
  every request without touching the visible conversation.

## Always on

Off by default. Turn it on with the flag file:

```bash
touch ~/.config/opencode/.i-have-autism-always
```

or for one process:

```bash
I_HAVE_AUTISM_ALWAYS=1 opencode
```

Turn it off for good by deleting the flag and unsetting the variable. Inside a
session, `stop autism mode` or `normal mode` suspends the rules for that session.
"""


def build() -> dict[Path, str]:
    name, description, body = skill_parts()
    command_description, command_template = command_parts()
    version = json.loads(PACKAGE.read_text(encoding="utf-8"))["version"]

    js = JS.format(
        name_json=json.dumps(name),
        description_json=json.dumps(description, ensure_ascii=False),
        body_json=json.dumps(body, ensure_ascii=False),
        command_description_json=json.dumps(command_description, ensure_ascii=False),
        command_template_json=json.dumps(command_template, ensure_ascii=False),
    )

    manifest = {
        "name": PLUGIN_NAME,
        "version": version,
        "description": description,
        "type": "module",
        "main": "i-have-autism.js",
        "exports": "./i-have-autism.js",
        "files": ["i-have-autism.js", "README.md", "skills"],
        "keywords": ["opencode", "opencode-plugin", "autism", "skills"],
        "license": "MIT",
        "repository": {"type": "git", "url": "https://github.com/Siririn77/i-have-autism"},
    }

    files = {
        OUT / "i-have-autism.js": js,
        OUT / "package.json": json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        OUT / "README.md": README.format(version=version),
        OUT / "skills" / "i-have-autism" / "SKILL.md": SKILL.read_text(encoding="utf-8"),
    }
    # SKILL.md ссылается на scripts/ и references/ — пакет обязан их нести,
    # иначе у читателя правило есть, а инструмента к нему нет.
    skill_dir = SKILL.parent
    for folder in ("scripts", "references"):
        for source in sorted((skill_dir / folder).glob("*")):
            if source.is_file():
                files[OUT / "skills" / "i-have-autism" / folder / source.name] = source.read_text(
                    encoding="utf-8"
                )
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the built package is stale")
    args = parser.parse_args()

    files = build()
    stale = [path for path, text in files.items() if not path.exists() or path.read_text(encoding="utf-8") != text]

    if args.check:
        if stale:
            print("stale opencode package; run tools/build_opencode_plugin.py:")
            for path in stale:
                print("  " + str(path.relative_to(ROOT)))
            return 1
        print("opencode package is current")
        return 0

    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print("wrote " + str(path.relative_to(ROOT)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
